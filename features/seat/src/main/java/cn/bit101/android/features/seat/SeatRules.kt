package cn.bit101.android.features.seat

/**
 * 座位系统的预约规则（展示用）。
 *
 * 来源：座位系统《预约规则》页（`/api/index/booking_rules` 原文要点），
 * 完整考证见 `docs/seatlib-contract.md` 第 10 节。
 *
 * ⚠️ 规则是**服务端可配置**的（例如「预约开始 X 分钟后无法取消」就是下发的
 * `seatcancel` 配置，具体数值我们拿不到）。所以这里展示的是**规则要点**，
 * 并在末尾注明「以图书馆最新公告为准」—— 别把它写成看起来像实时数据的断言。
 */
object SeatRules {

    /** 一条规则：[title] 是短标题，[body] 是说明。 */
    data class Rule(val title: String, val body: String)

    fun all(): List<Rule> = listOf(
        Rule(
            "可预约时间",
            "每天 6:00 起可预约当日或次日的座位；馆内开放时间为 08:00-22:30。",
        ),
        Rule(
            "签到",
            "预约当日：需在预约开始后 60 分钟内刷卡入馆（系统自动签到）；" +
                "预约次日：需在次日 9:00 前刷卡入馆。",
        ),
        Rule(
            "临时离开",
            "暂离后座位保留 60 分钟；用餐时段（11:00-12:00、16:00-17:00）延长至 120 分钟。" +
                "超时未回，座位自动释放并记违约 1 次。",
        ),
        Rule(
            "离开馆",
            "刷卡出馆后座位自动释放。",
        ),
        Rule(
            "取消预约",
            "每天可取消 2 次；预约开始一段时间后将无法取消（时长由馆方配置，以下单页提示为准）。",
        ),
        Rule(
            "违约",
            "预约后未签到记违约 1 次；各类违约累计 5 次，暂停预约权 7 天。",
        ),
    )

    /** 末尾的提示行（UI 展示时附在列表后面）。 */
    const val DISCLAIMER: String = "依据座位系统预约规则整理，以图书馆最新公告为准。"
}
