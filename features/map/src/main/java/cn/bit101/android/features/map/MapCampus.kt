package cn.bit101.android.features.map

/**
 * 地图页可切换的校区。
 *
 * ## 坐标怎么来的
 *
 * [x] / [y] 是 MapCompose 的**归一化坐标**（0..1，x 向东、y 向南），
 * 与瓦片服务 `map.bit101.flwfdd.xyz` 的**全球墨卡托**金字塔一一对应：
 *
 * ```
 * x = (lon + 180) / 360
 * y = 0.5 - ln(tan(45° + lat / 2)) / (2π)
 * ```
 *
 * 拿中关村校区验证过：现存的 `0.823083 / 0.37873` 反算是 `116.3099°E, 39.9584°N`，
 * 与「中关村南大街 5 号」的真实位置差 ~80 m —— 所以**坐标就是真实经纬度换算来的**，
 * 不需要靠试。
 *
 * ## ⚠️ 新增校区前必读
 *
 * 1. 瓦片服务**只提供 z15~z18**（更低级一律 403），也就是说低缩放看不到东西，
 *    坐标必须落准；先反算一遍经纬度（单测 `MapCampusTest` 里就有现成的换算），
 *    再去瓦片上「按图索骥」确认落点**真的有校区**（校园多边形 / 学院楼 / 体育场）
 * 2. **公开地图不渲染的地方别加**：西山实验区是国防实验区，地图上没有校区多边形，
 *    加了只会跳到一片普通居民区（2026-09-26 在瓦片上逐个查过，故未收录）
 * 3. 校名以学校口径为准（[name] 用于提示条与无障碍描述，[short] 只放一个汉字）
 * 4. **新校区（如嘉兴）大概率查不到现成坐标**，见下一节
 *
 * ## 查不到坐标怎么办（嘉兴校区就是这么定的）
 *
 * 嘉兴校区公开渠道**只有文字地址没有坐标**：招生章程写「油车港镇东方北路 1940 号」，
 * OSM / Nominatim / 高德百度的网页接口全都没有它，连瓦片底图都是**校园建成前**的数据
 * （2025 年才投用，底图上那儿还是农田）。这时最省事的是**借百度地图 POI 的分享链接**：
 *
 * 1. 手机百度地图搜到该地点 → 分享 → 复制链接，形如
 *    `https://map.baidu.com/?newmap=1&s=inf%26uid%3D<uid>&sharecallbackflag=poiDetailPage`
 *    ⚠️ 必须是**带 uid 的分享链接**；`s=inf&wd=<名称>`（按名称查）会**静默回落到北京视角**，
 *    看着像成功、其实给的是默认坐标（这个坑踩过）
 * 2. 用无头 Chromium 打开该链接，等 SPA 渲染完读 `location.href` —— 百度会把自己算好的
 *    坐标写进地址栏：`.../poi/<名称>/@<墨卡托x>,<墨卡托y>,19z?uid=...`
 *    （页面内 `fetch('?qt=inf&uid=...')` 会挂住，别走那条路；读地址栏即可）
 * 3. 该坐标是 **BD09-MC**，要依次 BD09-MC → BD09 → GCJ02 → WGS84。
 *    瓦片用的是 **WGS-84**，直接把 BD09 当 WGS84 用会**偏出约 1 km**
 *
 * 换算脚本与瓦片探针见 `.workbuddy/archive/tools/`（`map_tile_probe.py`）。
 *
 * ## 嘉兴校区最终怎么定的（有一个坑）
 *
 * - 官方地址 **浙江省嘉兴市秀洲区油车港镇东方北路 1940 号**（教育部中外合作办学批文与
 *   百度百科一致）；院区在**银杏天鹅湖**畔，紧邻杭州师范大学附属油车港中学的西侧，
 *   一期 500 亩（南区块已投用）
 * - ⚠️ **坑：百度 POI「北京理工大学长三角研究院」标的是院区东侧边缘，不是院区中心。**
 *   拿它的坐标直接用会偏出约 240 m（院区建筑群实测跨度约 570 m）
 * - 所以最终坐标是在百度**卫星图**上量出建筑群范围后取的中心。判据：卫星图上能直接看到
 *   院区建筑群（图书馆、圆形报告厅等），而**我们的瓦片底图比它旧**——那片还是农田与鱼塘。
 *   这**不是坐标错，是底图数据早于校园建成**（一期 2025 年交付）
 */
internal data class MapCampus(
    /** 完整名称，如 `中关村校区`；提示「已切换到…」时用 */
    val name: String,

    /** 按钮上的那个字，如 `村` */
    val short: String,

    /** 归一化横坐标（向东增大） */
    val x: Double,

    /** 归一化纵坐标（向南增大） */
    val y: Double,

    /** 定位时的缩放倍率 */
    val scale: Float = SCALE,
) {
    companion object {

        /** 定位时统一的缩放倍率（沿用改版前两个校区的取值）。 */
        const val SCALE = 0.25f

        /**
         * 全部校区。**顺序 = 按钮顺序**，第一个是进页面时的默认定位。
         *
         * 标注的是反算出来的**真实经纬度（WGS-84）**，便于日后核对/替换：
         * - 良乡校区  116.1666°E, 39.7290°N（房山区良乡高教园区）
         * - 中关村校区 116.3099°E, 39.9584°N（海淀区中关村南大街 5 号）
         * - 珠海校区  113.5370°E, 22.3708°N（香洲区唐家湾镇金凤路 6 号，原珠海学院）
         * - 嘉兴校区  120.7399°E, 30.8326°N（浙江嘉兴秀洲区油车港镇东方北路 1940 号，
         *             银杏天鹅湖畔；北理都灵理工学院办学地）
         */
        val ALL: List<MapCampus> = listOf(
            MapCampus(name = "良乡校区", short = "乡", x = 0.822685, y = 0.379560),
            MapCampus(name = "中关村校区", short = "村", x = 0.823083, y = 0.378730),
            MapCampus(name = "珠海校区", short = "珠", x = 0.815381, y = 0.436217),
            MapCampus(name = "嘉兴校区", short = "嘉", x = 0.835389, y = 0.409893),
        )
    }
}
